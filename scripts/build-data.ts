type Row = Record<string, unknown>      // one spreadsheet row, keyed by column letter
type CountryRows = {                    // each participant's row, keyed by iso3
  [iso3: string]: Row,
}
type Variable = {
  label: string,                        // what the site calls it
  oecd_average: object | null,          // null if the sheet has no OECD average
  countries: {
    [iso3: string]: object,
  },
}
type Sheet = {
  sheet_name: string,
  parse: (rows: Row[]) => {
    [variable: string]: Variable,
  },
}
type Spreadsheet = {
  file: string,
  sheets: Sheet[],
}

