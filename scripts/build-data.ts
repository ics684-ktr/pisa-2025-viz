/* Seven PISA codes aren't ISO3 codes, so Plotly's map can't place them. MAP_CODES swaps each
for its country's ISO3 code. Kosovo's "XKX" is a common stand-in, not an official ISO3 code,
and Plotly's map doesn't draw Kosovo, so the app shows it as a dot. */
const MAP_CODES: Record<string, string> = {
  QCI: "CHN", QCY: "CYP", QTJ: "TJK", KSV: "XKX", QKI: "IRQ", TAP: "TWN", QUA: "UKR",
}

/* The six countries that didn't meet PISA's sampling standards. */
const CAUTION = ["Albania", "Canada", "Netherlands", "New Zealand", "Norway", "United States"]

/* All PISA 2025 participants, keyed by iso3. */
const PARTICIPANTS: {
  [iso3: string]: {
    name: string,
    caution: boolean,
  }
} = {}
for (const [name, pisa_code] of Object.entries(PISA_CODES)) {
  const iso3 = MAP_CODES[pisa_code] ?? pisa_code
  PARTICIPANTS[iso3] = {
    name,
    caution: CAUTION.includes(name),
  }
}

const ISO3_BY_NAME = new Map(Object.entries(PARTICIPANTS).map(([iso3, { name }]) => [name, iso3]))

/* ---------- Building the JSON ---------- */

/* Checks what a sheet returned for one variable, whatever its layout: stops on a country code
that isn't a participant, and logs the OECD average and missing participants. */
function checkVariable({ oecd_average, countries }: Variable) {
  const unknown = Object.keys(countries).filter(iso3 => !(iso3 in PARTICIPANTS))
  if (unknown.length > 0) fail(`Not participants' iso3 codes: ${unknown.join(", ")}.`)

  /* A participant missing here may be spelled differently in this sheet than in PISA_CODES. */
  const missing = Object.keys(PARTICIPANTS).filter(iso3 => !(iso3 in countries))
  const names = (codes: string[]) => codes.map(iso3 => PARTICIPANTS[iso3].name).join(", ")

  console.log(`      OECD average: ${JSON.stringify(oecd_average)}`)
  console.log(`      ${Object.keys(countries).length} of ${Object.keys(PARTICIPANTS).length} participants`)
  if (missing.length > 0) {
    console.log(`      Missing: ${names(missing)}. ` +
      `If that's unexpected, check how this sheet spells them.`)
  }
}

function statLink(file: string) {
  return `https://stat.link/${path.parse(file).name}`
}

function fail(message: string): never {
  console.error(`Error: ${message}`)
  process.exit(1)
}

function main() {
  const files = SPREADSHEETS.map(spreadsheet => spreadsheet.file)
  const missing = files.filter(file => !fs.existsSync(path.join(DATA_DIR, file)))
  if (missing.length > 0) {
    console.error(`Missing spreadsheets in ${DATA_DIR}/: ${missing.join(", ")}. ` +
      `See ${DATA_DIR}/README.md for where to download them.`)
    process.exit(1)
  }

  console.log(`Found spreadsheets in ${DATA_DIR}/: ${files.join(", ")}`)

  const all_variables: Record<string, unknown> = {}

  for (const spreadsheet of SPREADSHEETS) {
    console.log(`Reading ${spreadsheet.file}`)
    const workbook: XLSX.WorkBook = XLSX.readFile(path.join(DATA_DIR, spreadsheet.file), {
      sheets: spreadsheet.sheets.map(sheet => sheet.sheet_name),
    })

    for (const { sheet_name, parse } of spreadsheet.sheets) {
      console.log(`  ${sheet_name}`)
      const worksheet = workbook.Sheets[sheet_name]
      if (!worksheet) fail(`Sheet "${sheet_name}" not found. Check its name in SPREADSHEETS.`)
      const rows = XLSX.utils.sheet_to_json<Row>(worksheet, { header: "A" })
      const variables = parse(rows)

      for (const [name, variable] of Object.entries(variables)) {
        if (name in all_variables) fail(`Duplicated variable: ${name}.`)
        console.log(`    ${name}`)
        checkVariable(variable)
        all_variables[name] = {
          label: variable.label,
          source: { table: sheet_name, statlink: statLink(spreadsheet.file) },
          oecd_average: variable.oecd_average,
          countries: variable.countries,
        }
      }
    }
  }

  const pisa_data = { PARTICIPANTS, VARIABLES: all_variables }
  fs.writeFileSync(OUTPUT_FILE, JSON.stringify(pisa_data, null, 2), "utf-8")
  console.log(`Wrote ${OUTPUT_FILE}`)
}

main()
