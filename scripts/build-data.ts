/* Every spreadsheet this script reads. Download links are in scripts/data/README.md. */
const SPREADSHEETS = [CHAPTER_4, CHAPTER_2]

/* ---------- Helpers for sheets ---------- */

/* The row whose `column` (A unless given) is `label`, e.g. "OECD average". Stops if there
isn't one. */
function findRow(rows: Row[], label: string, column = "A") {
  const row = rows.find(row => text(row[column]).trim() === label)
  if (!row) fail(`No row labelled "${label}" in column ${column}.`)
  return row
}

/* Every row that has a participant column, keyed by iso3. Stops if the sheet's "*" marks
disagree with CAUTION, since caution is stored once per participant in PARTICIPANTS. */
function findCountryRows(rows: Row[], column = "A") {
  const country_rows: CountryRows = {}
  const disagree: string[] = []

  for (const row of rows) {
    const country = parseCountry(text(row[column]))
    if (!country) continue
    country_rows[country.iso3] = row
    // Paranoid check to make sure the 6 countries have the caution flag
    if (country.caution !== PARTICIPANTS[country.iso3].caution) disagree.push(country.country)
  }

  if (disagree.length > 0) {
    fail(`This sheet marks caution ("*") differently from CAUTION for: ${disagree.join(", ")}.`)
  }
  return country_rows
}

/* Converts a raw country label into its participant's name, iso3 code and caution flag, or null
if the label isn't a participant. */
function parseCountry(label: string) {
  /* Strip "*" because countries ending with "*" didn't meet OECD's sampling criteria, so
  results should be treated with caution. */
  /* Strip the small numbers because they indicate footnotes in some spreadsheets, for example
  "United Kingdom²" in Table I.B1.4.81 */
  const country = label.trim().replace(/[*¹²³⁴⁵⁶⁷⁸⁹]+$/, "")
  const iso3 = ISO3_BY_NAME.get(country)
  if (iso3 === undefined) return null
  return { country, iso3, caution: label.includes("*") }
}

/* Turns { iso3: row } into { iso3: values }, using `parse` to pick the values out of each row. */
function mapRows(country_rows: CountryRows, parse: (row: Row) => object) {
  return Object.fromEntries(
    Object.entries(country_rows).map(([iso3, row]) => [iso3, parse(row)]),
  )
}

/* Some values have "m" or "c" indicating missing or insufficient data. */
const num = (v: unknown) => (typeof v === "number" ? v : null)
const text = (v: unknown) => (typeof v === "string" ? v : "")

/* "†" = the estimate covers 50–75% of the population. "‡" = than 50%.
Returning undefined instead of null makes it not show up in the JSON file. */
const flag = (v: unknown) => text(v) || undefined

